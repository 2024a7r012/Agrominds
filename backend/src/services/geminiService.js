const { geminiClient, modelName, isConfigured } = require('../config/gemini');
const logger = require('../config/logger');

const SYSTEM_INSTRUCTION = `You are "AgroMinds AI", an expert agricultural advisor and smart farming assistant for the AgroMinds platform.
Your mission is to assist farmers, agronomists, researchers, and students with practical, sustainable, and scientifically backed agricultural guidance.

Guidelines:
1. Focus strictly on agriculture, crop management, soil health, irrigation, fertilizers, pest control, weather impact, harvesting, post-harvest storage, and sustainable farming methods.
2. Structure your answers clearly with descriptive headings, bullet points, and step-by-step instructions.
3. Tailor recommendations to user context when provided (e.g. crop name, soil type, geographic region, growing stage).
4. Emphasize Integrated Pest Management (IPM), soil organic matter conservation, water conservation, and eco-friendly farming practices.
5. High-Risk Safety Disclaimer: Always include a safety reminder whenever recommending chemical pesticides or addressing severe crop diseases, advising consultation with local certified agricultural extension officers.
6. Tone: Respectful, practical, clear, encouraging, and farmer-friendly. Avoid overly dense academic jargon without explanation.`;

class GeminiService {
  /**
   * Generates response from Gemini API or falls back to transparent mock mode
   */
  async generateAdvice({ prompt, context = {}, conversationHistory = [] }) {
    const { crop, soil, location, growingStage } = context;

    // Build context string if provided
    let contextHeader = '';
    if (crop || soil || location || growingStage) {
      contextHeader = `[Context provided by farmer]: ${[
        crop ? `Crop: ${crop}` : '',
        soil ? `Soil: ${soil}` : '',
        location ? `Location/Region: ${location}` : '',
        growingStage ? `Growing Stage: ${growingStage}` : ''
      ].filter(Boolean).join(' | ')}\n\n`;
    }

    const fullPrompt = `${contextHeader}Farmer Query: ${prompt}`;

    // If Gemini is configured and client exists, try the live API
    if (isConfigured && geminiClient) {
      try {
        logger.info('Invoking Google Gemini API...', { model: modelName });

        // Format history if available
        const contents = [];
        if (Array.isArray(conversationHistory) && conversationHistory.length > 0) {
          for (const msg of conversationHistory.slice(-6)) {
            contents.push({
              role: msg.sender === 'user' ? 'user' : 'model',
              parts: [{ text: msg.content }]
            });
          }
        }
        contents.push({
          role: 'user',
          parts: [{ text: fullPrompt }]
        });

        const response = await geminiClient.models.generateContent({
          model: modelName,
          contents,
          config: {
            systemInstruction: SYSTEM_INSTRUCTION,
            temperature: 0.4
          }
        });

        const text = response?.text || response?.candidates?.[0]?.content?.parts?.[0]?.text;

        if (text) {
          return {
            content: text,
            is_mock: false,
            model_used: modelName,
            disclaimer: 'Generated by Google Gemini AI. Please verify chemical applications with local agricultural authorities.'
          };
        }
      } catch (err) {
        logger.error('Gemini API call failed, falling back to mock advisory:', { error: err.message });
        // Fall through to mock response with error indication
        return this.generateMockAdvice(prompt, context, `Gemini API error: ${err.message}`);
      }
    }

    // Explicit Mock Development Mode
    return this.generateMockAdvice(prompt, context, 'GEMINI_API_KEY is not configured in environment variables');
  }

  /**
   * Generates a high quality, explicitly labelled mock answer for local development
   */
  generateMockAdvice(prompt, context = {}, reason = 'Development Mode') {
    const crop = context.crop || 'your crop';
    const soil = context.soil || 'your soil type';
    const stage = context.growingStage || 'current stage';
    const location = context.location || 'your region';

    const mockContent = `### 🌾 AgroMinds Agricultural Advisory (Mock Mode)

> **Development Mode Notice**: This response was generated by AgroMinds local mock intelligence engine because: **${reason}**. Configure a valid \`GEMINI_API_KEY\` in your \`.env\` to enable live Google Gemini responses.

#### 1. Assessment for ${crop.toUpperCase()}
- **Target Condition**: Analysis based on **${soil}** in **${location}** during the **${stage}**.
- **Query Addressed**: "${prompt}"

#### 2. Recommended Agronomic Actions
- **Moisture & Irrigation**: Verify root zone moisture at 5-10 cm depth before scheduling water. For ${crop}, avoid standing water during sensitive vegetative transitions.
- **Nutrient Balancing**: Ensure balanced N-P-K supply. Supplement with organic compost or bio-fertilizers (e.g. *Azospirillum* or *PSB*) to foster microbial activity.
- **Canopy & Plant Health**: Inspect the undersides of leaves early in the morning for early signs of fungal lesions, sucking pests, or nutrient chlorosis.

#### 3. Integrated Crop Protection (IPM)
- Prefer cultural and biological controls first (e.g., neem seed kernel extract 5% or yellow sticky traps).
- Remove infected foliage or debris away from the primary cultivation plot.

---
⚠️ **Agricultural Safety Disclaimer**: Advice provided is for educational reference. High-risk chemical pesticide applications or severe disease outbreaks must always be verified with certified local agronomy extension officers.`;

    return {
      content: mockContent,
      is_mock: true,
      mock_reason: reason,
      model_used: 'AgroMinds-Local-Mock-Engine',
      disclaimer: 'Simulated agricultural response for testing without active Gemini API keys.'
    };
  }
}

module.exports = new GeminiService();
